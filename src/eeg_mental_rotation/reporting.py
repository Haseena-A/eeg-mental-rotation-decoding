"""Write the research report from files the pipeline actually produced.

Sections that have not been run stay marked as not yet computed. Numbers are
read from the results directory and are never filled in by hand.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def _load(path: Path) -> Any:
    if not path.exists():
        return None
    if path.suffix == ".json":
        return json.loads(path.read_text(encoding="utf-8"))
    return path.read_text(encoding="utf-8")


def write_report(results_dir: Path, destination: Path) -> Path:
    inventory = _load(results_dir / "dataset_inventory.json")
    quality = _load(results_dir / "quality_report.json")
    sync = _load(results_dir / "synchronization_report.json")
    models = _load(results_dir / "model_results.json")
    lines = [
        "# EEG and mental-rotation performance",
        "",
        "This report is generated by `scripts/generate_report.py`.",
        "A section says **not yet computed** until the corresponding pipeline stage has been run on the downloaded recordings.",
        "No result in this file is typed in by hand.",
        "",
        "## Dataset inventory",
        "",
    ]
    if not inventory:
        lines.append("**Not yet computed.** Run `python scripts/validate_dataset.py` after downloading the Figshare archive.")
    else:
        lines.append(f"Participant folders found: {inventory.get('n_participant_folders')}.")
        lines.append("")
        lines.append("The published paper reports 38 participants. A difference is a property of the local copy, not a correction of the paper.")
    lines.extend(["", "## Recording quality", ""])
    if not quality:
        lines.append("**Not yet computed.**")
    elif isinstance(quality, list):
        rates = []
        for row in quality:
            sampling = ((row.get("eeg") or {}).get("sampling") or {})
            rate = sampling.get("sampling_rate_hz")
            if isinstance(rate, (int, float)):
                rates.append(float(rate))
        lines.append(f"Participants assessed: {len(quality)}.")
        if rates:
            lines.append(
                f"Per-participant median-interval rate: min {min(rates):.2f} Hz, "
                f"median {sorted(rates)[len(rates)//2]:.2f} Hz, max {max(rates):.2f} Hz."
            )
        lines.append("Full per-participant tables are in `results/tables/quality_report.json`.")
    if sync and isinstance(sync, dict):
        statuses: dict[str, int] = {}
        for row in sync.get("participants") or []:
            decision = row.get("preprocessing") or {}
            status = decision.get("status") or "unknown"
            statuses[status] = statuses.get(status, 0) + 1
        if statuses:
            lines.append("Preprocessing decisions: " + ", ".join(f"{name}={count}" for name, count in sorted(statuses.items())) + ".")
            lines.append(
                "A median interval near 1 ms is not used as a sampling rate when the 95th percentile interval is much longer. "
                "Models use the vendor band-power columns. Raw spectra, including any file that was filtered because it fell just under the cutoff, are not model features."
            )
    lines.extend(["", "## Synchronization", ""])
    if not sync:
        lines.append("**Not yet computed.** Trial-level models are not run until this section shows accepted alignment.")
    else:
        lines.append(f"Decision: `{sync.get('level')}` with coverage {sync.get('coverage')}.")
        lines.append("")
        lines.append(sync.get("reason", ""))
    lines.extend(["", "## Models", ""])
    if not models:
        lines.append("**Not yet computed.**")
    else:
        for result in models:
            if result.get("status") != "ok":
                lines.append(f"- {result.get('task')} / {result.get('kind')} / {result.get('estimator')}: not run ({result.get('reason')})")
                continue
            summary = result.get("summary", {})
            metric = "balanced_accuracy" if result.get("task") == "classification" else "mae"
            value = summary.get(metric, {})
            lines.append(
                f"- {result['task']} / {result['kind']} / {result['estimator']}: "
                f"{metric} mean {value.get('mean'):.3f} (sd {value.get('std'):.3f}) "
                f"over {result.get('n_splits')} participant-independent folds."
            )
    lines.extend(
        [
            "",
            "## Interpretation boundary",
            "",
            "A model that predicts whether a response was correct does not decode the mental rotation.",
            "Feature importance is a statement about the fitted model, not about a cortical mechanism.",
            "Four Muse channels do not support source localization.",
            "",
        ]
    )
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines), encoding="utf-8")
    return destination
